export interface MediaRef {
  src: string;
  caption: string;
  credit: string;
}

export type SheetBlock =
  | { type: 'text'; text: string[] }
  | { type: 'fact'; items: string[] }
  | { type: 'stats'; items: { value: string; label: string }[] }
  | { type: 'photo'; media: MediaRef }
  | { type: 'video'; media: MediaRef };

export interface SubSection {
  id: string;
  title: string;
  meta: string;
  blocks: SheetBlock[];
}

export interface Part {
  id: string;
  numeral: string; // римская цифра части (как в оглавлении пользователя)
  order: string; // порядок на странице «все части»
  theme: string; // моно-метка
  listTitle: string; // короткое название для списка всех частей
  title: string;
  titleAccent: string; // вторая строка заголовка (серым/зелёным)
  dates: string; // тег с датами
  intro: string; // вводный абзац-плейсхолдер
  stats: { value: string; label: string }[];
  heroMedia: MediaRef; // кадр в обзоре «Все части»
  heroVideo?: boolean;
  subsections: SubSection[];
}

